-- Rode no Oracle antes de subir a API.
-- O aviso do cidadão não existia na entrega de database.
-- Quem grava a linha é o consumidor do RabbitMQ, depois da validação.

CREATE TABLE tb_pg_notificacao (
    id_notificacao NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     NUMBER NOT NULL,
    id_descarte    NUMBER NOT NULL,
    st_validacao   VARCHAR2(30) NOT NULL,
    ds_mensagem    VARCHAR2(300) NOT NULL,
    dt_criacao     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_pg_notificacao_usuario FOREIGN KEY (id_usuario) REFERENCES tb_pg_usuario (id_usuario),
    CONSTRAINT ck_pg_notificacao_status CHECK (st_validacao IN ('VALIDADO_IA', 'REJEITADO'))
);
